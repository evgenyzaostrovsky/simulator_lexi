export function insertCommas(text) {
  const clean = text.replaceAll(',', '');
  const boundaries = [...clean.matchAll(/[\p{L}\p{N}](?=\s+\S)/gu)].map(match => match.index + 1);
  for (let i = boundaries.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [boundaries[i], boundaries[j]] = [boundaries[j], boundaries[i]];
  }
  const chosen = new Set(boundaries.slice(0, Math.max(0, Math.min(500 - clean.length, Math.max(1, Math.floor(boundaries.length / 3))))));
  return clean.split('').map((char, index) => char + (chosen.has(index + 1) ? ',' : '')).join('');
}
